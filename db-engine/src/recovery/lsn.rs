// src/recovery/lsn.rs
//
// 【模块职责】
// 定义日志序列号 LSN —— WAL 与 ARIES 恢复的"时间轴"。
// 类比 Java：相当于一个全局单调递增的 timestamp/version 号。
//
// 【工业化语义：LSN = 物理字节偏移量】
// 借鉴 MySQL InnoDB：LSN 不再是纯自增计数器，而是"系统启动以来产生的日志字节总量"。
// - 一条日志记录的 LSN = 该记录在日志流中的【结束偏移量】
//   （分配规则：新 LSN = 旧 LSN + 本记录序列化后的总字节数）
// - 因此 pageLSN 可直接映射到日志文件的物理位置，恢复期寻址无需从头扫描。
// - LSN 依然全局单调递增（字节总量只增不减），重启时通过扫描日志恢复，不丢失、不回退。

/// 日志序列号：本质是日志流的字节偏移量（全局单调递增）
pub type Lsn = u64;

/// 无效 LSN：表示"没有前驱日志"或"全新页尚未被任何日志修改"。
///
/// 采用「记录结束偏移」语义后，任何真实记录的 LSN 都 >= 其自身字节数 > 0，
/// 因此 0 天然可作哨兵值，且不会与有效 LSN 冲突。
pub const INVALID_LSN: Lsn = 0;